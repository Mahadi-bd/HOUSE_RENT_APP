#!/usr/bin/env python3
"""Writes lib/firebase_options.dart from android/app/google-services.json, so you only have to
download ONE file from the Firebase console. With --placeholder it writes fake values (and a fake
google-services.json if missing) so the app still COMPILES and the tests run in GitHub before
the real file is added. A placeholder build cannot talk to Firebase."""
import json
import os
import sys

GS = "android/app/google-services.json"
OUT = "lib/firebase_options.dart"
PACKAGE = "com.rentsolution.app"


def placeholder_json():
    return {
        "project_info": {"project_number": "000000000000", "project_id": "placeholder-not-real", "storage_bucket": "placeholder-not-real.appspot.com"},
        "client": [
            {
                "client_info": {"mobilesdk_app_id": "1:000000000000:android:0000000000000000", "android_client_info": {"package_name": PACKAGE}},
                "api_key": [{"current_key": "PLACEHOLDER_NOT_A_REAL_KEY"}],
                "services": {"appinvite_service": {"other_platform_oauth_client": []}},
            }
        ],
        "configuration_version": "1",
    }


def main():
    placeholder = "--placeholder" in sys.argv
    if not os.path.exists(GS):
        if not placeholder:
            print(f"{GS} not found", file=sys.stderr)
            return 1
        os.makedirs(os.path.dirname(GS), exist_ok=True)
        with open(GS, "w", encoding="utf-8") as f:
            json.dump(placeholder_json(), f, indent=2)
    data = json.load(open(GS, encoding="utf-8"))
    info = data["project_info"]
    client = next((c for c in data["client"] if c["client_info"]["android_client_info"]["package_name"] == PACKAGE), None)
    if client is None:
        print(f"google-services.json has no Android app with package {PACKAGE}. Add that app in the Firebase console and download the file again.", file=sys.stderr)
        return 1
    code = f"""// GENERATED by tools/make_firebase_options.py from android/app/google-services.json. Do not edit.
// Android only. iPhone support needs `flutterfire configure` on a Mac.
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

/// Firebase settings for this build.
class DefaultFirebaseOptions {{
  /// Options for the current platform.
  static FirebaseOptions get currentPlatform {{
    if (!kIsWeb && defaultTargetPlatform == TargetPlatform.android) {{
      return android;
    }}
    throw UnsupportedError('Firebase is configured for Android only in this build.');
  }}

  /// Android options.
  static const FirebaseOptions android = FirebaseOptions(
    apiKey: '{client["api_key"][0]["current_key"]}',
    appId: '{client["client_info"]["mobilesdk_app_id"]}',
    messagingSenderId: '{info["project_number"]}',
    projectId: '{info["project_id"]}',
    storageBucket: '{info.get("storage_bucket", "")}',
  );
}}
"""
    os.makedirs("lib", exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(code)
    print(f"wrote {OUT} for project {info['project_id']}{' (PLACEHOLDER)' if placeholder else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
